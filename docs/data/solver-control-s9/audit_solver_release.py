"""Audit the portable scoped solver-control release evidence without a build."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import tarfile

REQUIRED={'native','python','parity','policy','campaign','artifacts'}


def read(path):return json.loads(path.read_text())
def digest(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda:f.read(1024*1024),b''):h.update(block)
    return h.hexdigest()
def require(ok,message):
    if not ok:raise ValueError(message)


def verify_manifest(root,manifest):
    for name,value in manifest['files'].items():
        require('__pycache__' not in Path(name).parts and not name.endswith('.pyc'),'Generated bytecode in release manifest')
        require(digest(root/name)==value,'Changed release evidence: '+name)
    for archive,index in manifest.get('sources',{}).items():
        with tarfile.open(root/archive) as a:
            for name,value in index.items():
                require(hashlib.sha256(a.extractfile(name).read()).hexdigest()==value,'Changed release source member: '+name)


def validate_summary(summary,scope):
    require(set(summary['checks'])==REQUIRED,'Incomplete release validation gates')
    require(all(row['passed'] for row in summary['checks'].values()),'Release gate failed')
    require(scope['closure']=='qualified-pedestrian-solver-control-refactor','Wrong closure scope')
    require('deferred explicitly by user' in scope['stages']['S8b'],'S8b disposition missing')
    require(scope['defaults']['solver_control'] is None and scope['defaults']['relaxation']==1.78,'Default promotion is outside this closure')
    require(scope['policy']['native_revision']==summary['native_policy_revision'],'Native policy identity changed')
    require(summary['checks']['parity']['comparisons']==12 and summary['checks']['parity']['cases']==429,'Incomplete default parity matrix')
    require(summary['checks']['policy']['workers']==24 and summary['checks']['policy']['exact_workers']==24,'Incomplete policy regression')
    require(summary['checks']['campaign']['fresh_results'] and summary['checks']['campaign']['reused'] and summary['checks']['campaign']['damaged_package_rebuilt'],'Campaign reuse/rebuild gate incomplete')


def compare_fingerprints(expected,actual):
    # Module import location is provenance, not a numerical result. Every other
    # array must keep dtype, shape and complete bytes exactly.
    a={k:v for k,v in expected.items() if k!='_module'}
    b={k:v for k,v in actual.items() if k!='_module'}
    require(a==b,'Default array fingerprint mismatch')


def audit(root,prior_root=None):
    manifest=read(root/'manifest.json');verify_manifest(root,manifest)
    summary=read(root/'validation.json');scope=read(root/'scope.json');validate_summary(summary,scope)
    parity=read(root/'parity/report.json')
    require(parity['passed'] and len(parity['comparisons'])==12,'Default parity report failed')
    require(all(not r['differences'] for r in parity['comparisons']),'Default numerical differences')
    require({r['threads'] for r in parity['comparisons'] if r['kind']=='revision' and r['backend']=='openmp'}=={1,2,4,8},'Missing default team coverage')
    fingerprints=read(root/'parity/array-fingerprints.json')
    baseline=read(root/'parity/baseline-array-fingerprints.json')
    normalized=read(root/'parity/backend-independent-fingerprints.json')
    for backend,teams in [('openmp',[1,2,4,8]),('serial',[1])]:
        for team in teams:
            compare_fingerprints(baseline[f'archive-f138616b7796-{backend}-{team}threads.npz']['members'],fingerprints[f'{backend}-{team}.npz'])
            compare_fingerprints(normalized['openmp-1.npz'],normalized[f'{backend}-{team}.npz'])
    policy=read(root/'policy/summary.json')
    require(policy['passed'] and policy['workers']==24 and policy['exact_workers']==24,'Policy output identity regression')
    prior=read(root/'prior-evidence.json')
    s7=read(root/'parity/s7-manifest.json')
    require(digest(root/'parity/s7-manifest.json')==prior['solver-control-s7']['manifest_sha256'],'Baseline fingerprint provenance changed')
    require(digest(root/'parity/baseline-array-fingerprints.json')==s7['files']['validation/default-array-fingerprints.json'],'Baseline array fingerprints changed')
    checked=0
    if prior_root is not None:
        for name,value in prior.items():
            require(digest(prior_root/name/'manifest.json')==value['manifest_sha256'],'Prior evidence identity changed: '+name)
            m=read(prior_root/name/'manifest.json')
            for rel,expected in m['files'].items():require(digest(prior_root/name/rel)==expected,'Prior evidence file changed: '+name+'/'+rel)
            checked+=1
    return dict(passed=True,closure=scope['closure'],s8b='deferred_by_user',gates=sorted(REQUIRED),
        native_policy_revision=summary['native_policy_revision'],prior_evidence_bundles_verified=checked,
        prior_bundles_recorded=len(prior),default_comparisons=12,policy_workers=24)


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('evidence',type=Path)
    ap.add_argument('--prior-root',type=Path,help='Also verify unchanged prior evidence bundles under docs/data')
    args=ap.parse_args();print(json.dumps(audit(args.evidence,args.prior_root),indent=2))
